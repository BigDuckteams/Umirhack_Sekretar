"""Категория вопроса для статистики: по ключевым словам, без сохранения самого текста вопроса."""

from __future__ import annotations

import re

OTHER = "Другое"

# порядок важен: более конкретные темы раньше общих
TOPICS = (
    ("Академический отпуск", re.compile(r"академ|отпуск")),
    ("Перевод из другого вуза", re.compile(r"перевод|перевест|перейти|переход")),
    ("Поступление и зачисление", re.compile(r"поступ|зачисл|абитуриент|приёмн|приемн")),
    ("Практика", re.compile(r"практик")),
    ("Справка об обучении", re.compile(r"справк\w*\s+об\s+обучени|справк\w*\s+с\s+места|подтвержд\w+\s+обучени")),
    ("Сроки рассмотрения", re.compile(r"срок|в течение|за сколько|сколько дн|рабоч\w+\s+дн|как долго|когда\s+(?:ответ|рассмотр)")),
    ("Стоимость и стипендия", re.compile(r"стоимост|сколько стоит|стоит ли|цена|оплат|стипенд|платн|бесплатн|скидк|кредит")),
    ("Общежитие", re.compile(r"общежит")),
    ("Документы и требования", re.compile(r"документ|справк|заявлени|подпис|печат|реквизит|нотариал|скан|фото")),
)


def classify_topic(question: str) -> str:
    t = re.sub(r"\s+", " ", (question or "").lower().replace("ё", "е"))
    if not t.strip():
        return "Проверка документа"
    for title, rx in TOPICS:
        if rx.search(t):
            return title
    return OTHER


def all_topics() -> list[str]:
    return [t for t, _ in TOPICS] + ["Проверка документа", OTHER]
