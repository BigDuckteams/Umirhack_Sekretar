def page_from_text(text: str) -> OcrPage:
    words, y = [], 20.0
    for line in text.split("\n"):
        x = 20.0
        for tok in line.split():
            words.append(Word(tok, 95.0, x, y, x + 9.0 * len(tok), y + 22.0))
            x += 9.0 * len(tok) + 8.0
        y += 40.0
    return OcrPage(0, 1200, 1700, words, build_rows(words), np.eye(3), (1200, 1700))


def main() -> int:
    types = load_doc_types(load_settings().doc_types_dir)
    bad = total = 0
    for want, texts in CASES.items():
        for t in texts:
            c = classify(types, [page_from_text(t)])
            total += 1
            ok = c.type_id == want
            bad += not ok
            print(f"{'OK ' if ok else 'ERR'} ждали {want:22s} получили {str(c.type_id):22s} conf={c.confidence:.2f} unc={c.uncertain!s:5s} {c.features}  «{t[:40].strip()}…»")
    print(f"Наши документы: верно {total - bad}/{total}")
    rejected = 0
    for t in FOREIGN:
        c = classify(types, [page_from_text(t)])
        rejected += c.type_id is None
        print(f"{'OK ' if c.type_id is None else 'ERR'} посторонний документ -> {c.type_id}  {c.features}  «{t[:40].strip()}…»")
    print(f"Посторонние отвергнуты: {rejected}/{len(FOREIGN)}")
    return 0 if (not bad and rejected == len(FOREIGN)) else 1


